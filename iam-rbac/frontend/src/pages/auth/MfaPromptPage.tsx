import React, { useState } from 'react';
import { flushSync } from 'react-dom';
import { useLocation, useNavigate, Link } from 'react-router-dom';
import { authApi } from '../../api/auth';
import { useAuth } from '../../context/AuthContext';
import { ShieldCheck, KeyRound, ArrowLeft } from 'lucide-react';

interface MfaLocationState {
  mfaSessionToken?: string;
  userType?: 'root' | 'iam';
  identifier?: string;
}

export function MfaPromptPage() {
  const navigate = useNavigate();
  const location = useLocation();
  const { loginUser } = useAuth();
  const state = (location.state as MfaLocationState) || {};

  const mfaSessionToken = state.mfaSessionToken;
  const identifier = state.identifier || 'User';

  const [code, setCode] = useState('');
  const [useBackupCode, setUseBackupCode] = useState(false);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  if (!mfaSessionToken) {
    return (
      <div className="min-h-screen bg-aws-lightbg dark:bg-aws-darkBg flex items-center justify-center p-4">
        <div className="bg-white dark:bg-aws-darkCard p-6 rounded-lg border border-gray-200 dark:border-gray-800 text-center max-w-sm">
          <p className="text-sm text-gray-700 dark:text-gray-300 mb-4">
            MFA session expired or missing. Please sign in again.
          </p>
          <Link
            to="/signin"
            className="inline-block py-2 px-4 bg-aws-orange hover:bg-aws-orangeHover text-black font-bold rounded text-xs"
          >
            Go to Sign-in
          </Link>
        </div>
      </div>
    );
  }

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);
    setLoading(true);

    try {
      const res = await authApi.mfaVerify({
        mfaSessionToken,
        code: code.trim(),
        isBackupCode: useBackupCode,
      });

      if (res.success && res.data?.user) {
        flushSync(() => {
          loginUser(res.data.user);
        });
        navigate('/dashboard', { replace: true });
      }
    } catch (err: any) {
      setError(err.message || 'Invalid MFA code. Please try again.');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="min-h-screen bg-aws-lightbg dark:bg-aws-darkBg flex flex-col justify-between p-4 py-8 text-aws-text dark:text-gray-100">
      <div className="max-w-md w-full mx-auto my-auto">
        {/* Brand Header */}
        <div className="text-center mb-6">
          <div className="inline-flex items-center gap-2 mb-2">
            <div className="h-8 w-8 rounded bg-gradient-to-br from-aws-orange to-aws-orangeHover flex items-center justify-center font-black text-black text-sm shadow">
              M
            </div>
            <span className="font-black text-2xl tracking-tight text-aws-navy dark:text-white">
              AWS
            </span>
          </div>
          <h1 className="text-xl font-bold text-gray-900 dark:text-white">
            Multi-factor authentication
          </h1>
        </div>

        {/* Card */}
        <div className="bg-white dark:bg-aws-darkCard border border-gray-200 dark:border-aws-darkBorder rounded-lg p-6 sm:p-8 shadow-xl">
          <div className="mb-5 flex items-center gap-3 p-3 rounded bg-blue-50/70 dark:bg-blue-950/30 border border-blue-200 dark:border-blue-900/40">
            {useBackupCode ? (
              <KeyRound className="w-5 h-5 text-blue-600 dark:text-blue-400 flex-shrink-0" />
            ) : (
              <ShieldCheck className="w-5 h-5 text-blue-600 dark:text-blue-400 flex-shrink-0" />
            )}
            <div className="text-xs text-gray-700 dark:text-gray-300">
              <span className="font-bold text-gray-900 dark:text-white block">
                Two-Factor Security Enforced
              </span>
              Verify your identity for <span className="font-semibold">{identifier}</span>.
            </div>
          </div>

          <form onSubmit={handleSubmit} className="space-y-5 text-xs">
            {error && (
              <div className="p-3 bg-red-50 dark:bg-red-950/30 border border-red-200 dark:border-red-900/50 rounded text-red-600 dark:text-red-400 font-medium">
                {error}
              </div>
            )}

            {!useBackupCode ? (
              <div className="space-y-2">
                <label className="block font-bold text-gray-700 dark:text-gray-300">
                  Authentication code
                </label>
                <p className="text-[11px] text-gray-500">
                  Enter the 6-digit code generated by your authenticator app.
                </p>
                <input
                  type="text"
                  required
                  autoFocus
                  maxLength={6}
                  placeholder="123456"
                  value={code}
                  onChange={(e) => setCode(e.target.value.replace(/\D/g, ''))}
                  className="w-full text-center text-xl tracking-[0.3em] font-mono p-3 border border-gray-300 dark:border-gray-600 rounded bg-white dark:bg-black/40 text-gray-900 dark:text-white focus:outline-none focus:border-aws-orange"
                />
              </div>
            ) : (
              <div className="space-y-2">
                <label className="block font-bold text-gray-700 dark:text-gray-300">
                  One-time backup emergency code
                </label>
                <p className="text-[11px] text-gray-500">
                  Enter one of your 8-character backup codes generated during setup.
                </p>
                <input
                  type="text"
                  required
                  autoFocus
                  maxLength={12}
                  placeholder="A1B2C3D4"
                  value={code}
                  onChange={(e) => setCode(e.target.value.toUpperCase())}
                  className="w-full text-center text-lg tracking-widest font-mono p-3 border border-gray-300 dark:border-gray-600 rounded bg-white dark:bg-black/40 text-gray-900 dark:text-white focus:outline-none focus:border-aws-orange uppercase"
                />
              </div>
            )}

            <button
              type="submit"
              disabled={loading || code.trim().length === 0}
              className="w-full py-2.5 px-4 bg-aws-orange hover:bg-aws-orangeHover text-black font-extrabold rounded shadow-sm transition-colors cursor-pointer disabled:opacity-50 text-xs"
            >
              {loading ? 'Verifying...' : 'Submit'}
            </button>

            <div className="flex items-center justify-between pt-3 border-t border-gray-200 dark:border-gray-700">
              <button
                type="button"
                onClick={() => {
                  setUseBackupCode(!useBackupCode);
                  setCode('');
                  setError(null);
                }}
                className="text-aws-blue dark:text-cyan-400 hover:underline text-[11px] font-semibold cursor-pointer"
              >
                {useBackupCode ? 'Use authenticator app instead' : 'Lost your phone? Use backup code'}
              </button>

              <Link
                to="/signin"
                className="text-gray-500 hover:text-gray-700 dark:hover:text-gray-300 flex items-center gap-1 text-[11px]"
              >
                <ArrowLeft className="w-3 h-3" />
                Cancel
              </Link>
            </div>
          </form>
        </div>
      </div>

      <footer className="text-center text-[11px] text-gray-500 mt-6">
        © 2026, Amazon Web Services, Inc. or its affiliates. All rights reserved.
      </footer>
    </div>
  );
}
