interface IndicLanguageContextType {
  language: string;
  setLanguage: (code: string) => void;
  currentLanguage: IndicLanguage;
  languages: IndicLanguage[];
  t: (key: string, fallback?: string) => string;
  isIndicLanguage: boolean;
}

const IndicLanguageContext = createContext<IndicLanguageContextType | undefined>(undefined);

const LOCAL_STORAGE_KEY = 'mipaas_indic_language';

// Intelligent English -> Indic language translation index (O(1) fast lookup)
const ENGLISH_TO_TRANSLATION_MAP = new Map<string, Record<string, string>>();
for (const [, langMap] of Object.entries(UI_TRANSLATIONS)) {
  if (langMap.en) {
    ENGLISH_TO_TRANSLATION_MAP.set(langMap.en.trim().toLowerCase(), langMap);
  }
}

export function IndicLanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<string>('en');

  useEffect(() => {
    try {
      const saved = localStorage.getItem(LOCAL_STORAGE_KEY);
      if (saved && INDIC_LANGUAGES.some((l) => l.code === saved)) {
        setLanguageState(saved);
      }
    } catch {}
  }, []);

  const setLanguage = (code: string) => {
    setLanguageState(code);
    try {
      localStorage.setItem(LOCAL_STORAGE_KEY, code);
    } catch {}
  };

  const currentLanguage =
    INDIC_LANGUAGES.find((l) => l.code === language) || INDIC_LANGUAGES[0];

  const t = (key: string, fallback?: string): string => {
    if (language === 'en') {
      return fallback || (UI_TRANSLATIONS[key]?.en ?? key);
    }
    // 1. Exact key match
    const entry = UI_TRANSLATIONS[key];
    if (entry && entry[language]) {
      return entry[language];
    }
    // 2. Direct English fallback text lookup
    if (fallback) {
      const mapped = ENGLISH_TO_TRANSLATION_MAP.get(fallback.trim().toLowerCase());
      if (mapped && mapped[language]) {
        return mapped[language];
      }
    }
    // 3. Fallback when key itself is English text (e.g. t('Patients'), t('Appointments'))
    const keyMapped = ENGLISH_TO_TRANSLATION_MAP.get(key.trim().toLowerCase());
    if (keyMapped && keyMapped[language]) {
      return keyMapped[language];
    }
    return fallback || (entry?.['en'] ?? key);
  };

  const isIndicLanguage = language !== 'en';

  return (
    <IndicLanguageContext.Provider
      value={{
        language,
        setLanguage,
        currentLanguage,
        languages: INDIC_LANGUAGES,
        t,
        isIndicLanguage,
      }}
    >
      {children}
    </IndicLanguageContext.Provider>
  );
}

export function useIndicLanguage() {
  const context = useContext(IndicLanguageContext);
  if (!context) {
    throw new Error('useIndicLanguage must be used within an IndicLanguageProvider');
  }
  return context;
}
